#!/usr/bin/env node
/**
 * Generate the Claude Code plugin under `plugins/builderforce-memory/`.
 *
 * The memory combo already existed as an INSTALLER (`builderforce-memory-install`)
 * that mutates a user's `~/.claude`. A Claude Code *plugin* is the same combo in
 * declarative form: a directory Claude Code loads directly, which is what makes
 * it listable in a plugin marketplace and installable with `/plugin install`.
 *
 * The plugin's hook script and companion skill are GENERATED from the very same
 * `claude-hooks.ts` functions the installer uses, so the two delivery shapes can
 * never drift. Regenerate with `pnpm plugin:build`; CI re-runs it and fails on a
 * diff, so an edit to the hook source cannot ship a stale plugin.
 *
 * Usage:  node scripts/build-claude-plugin.mjs [--check]
 *         --check  verify the committed output matches; write nothing.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { emitFiles, pathToFileUrl } from "./lib/emit.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MCP_DIST = path.join(ROOT, "packages", "memory-mcp", "dist");
const PLUGIN_DIR = path.join(ROOT, "plugins", "builderforce-memory");
const CHECK = process.argv.includes("--check");

if (!fs.existsSync(path.join(MCP_DIST, "install", "claude-hooks.js"))) {
  console.error("✗ packages/memory-mcp is not built. Run `pnpm -r build` first.");
  process.exit(1);
}

const { bfmemHookSource, companionSkillMd, pluginHooksConfig } = await import(
  pathToFileUrl(path.join(MCP_DIST, "install", "claude-hooks.js"))
);
const { MCP_PACKAGE, MCP_BIN, RUNTIME_PEERS } = await import(
  pathToFileUrl(path.join(MCP_DIST, "install", "server-spec.js"))
);

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "packages", "memory-mcp", "package.json"), "utf8"));

/**
 * The plugin registers the SAME published stdio server the installer does, via
 * npx. It deliberately sets no `BUILDERFORCE_MEMORY_FILE`: the bin and the hook
 * script both fall back to the shared per-machine store, so a plugin install and
 * an installer install address one memory, not two.
 *
 * `npx` on Windows is a `.cmd` shim, but a plugin manifest is one static file
 * shared across platforms — so it uses the portable `npx` form and relies on
 * Claude Code's own launcher, rather than the platform-specific `cmd /c` wrapper
 * the installer writes into a machine's config.
 */
const mcpServers = {
  "builderforce-memory": {
    command: "npx",
    args: ["-y", "-p", MCP_PACKAGE, ...RUNTIME_PEERS.flatMap((p) => ["-p", p]), MCP_BIN],
  },
};

const manifest = {
  $schema: "https://json.schemastore.org/claude-code-plugin-manifest.json",
  name: "builderforce-memory",
  displayName: "Builderforce Memory",
  version: pkg.version,
  description:
    "Token-saving persistent memory for Claude Code. Recall durable facts instead of re-reading files or history, "
    + "with a session digest, contextual per-prompt recall, and autonomous capture of corrections you would otherwise repeat.",
  author: { name: "Sean Hogg", email: "seanhogg@gmail.com", url: "https://builderforce.ai" },
  homepage: "https://github.com/SeanHogg/builderforce-memory/tree/main/plugins/builderforce-memory#readme",
  repository: "https://github.com/SeanHogg/builderforce-memory",
  license: "MIT",
  keywords: ["memory", "mcp", "context", "token-savings", "recall", "persistence"],
  hooks: "./hooks/hooks.json",
  mcpServers,
};

const files = {
  ".claude-plugin/plugin.json": `${JSON.stringify(manifest, null, 2)}\n`,
  "hooks/hooks.json": `${JSON.stringify({ hooks: pluginHooksConfig() }, null, 2)}\n`,
  // `null` → the script resolves the snapshot path at run time. A plugin ships
  // one file to every machine, so no path may be baked in.
  "hooks/bfmem-hook.mjs": bfmemHookSource(null),
  "skills/builderforce-memory/SKILL.md": companionSkillMd(),
  "README.md": readme(pkg.version),
};

emitFiles(PLUGIN_DIR, files, {
  check: CHECK,
  label: "plugins/builderforce-memory",
  fixHint: "run `pnpm plugin:build` and commit the result",
});

function readme(version) {
  return `# Builderforce Memory — Claude Code plugin

Persistent, token-saving memory for Claude Code. Version ${version}.

> Generated by \`scripts/build-claude-plugin.mjs\` from the same source as the
> \`builderforce-memory-install\` CLI. Do not edit these files by hand.

## Install

\`\`\`
/plugin marketplace add SeanHogg/builderforce-memory
/plugin install builderforce-memory@builderforce
\`\`\`

## What you get

The MCP server gives Claude the memory **tools**; the four hooks are what make it
self-driving, so you never have to remember to use it:

| Hook | Event | Behaviour |
| --- | --- | --- |
| \`--session\` | SessionStart | Injects a digest of your top durable memories. |
| \`--recall\` | UserPromptSubmit | Scores memories against the prompt and injects the relevant ones — retrieval at the decision point, not just at startup. |
| \`--capture\` | Stop | Detects a durable instruction or correction you gave and blocks the stop until it is persisted. |
| \`--precompact\` | PreCompact | Flushes durable learnings before the window is summarised. |

Each memory is injected at most once per session, so a long session does not
re-inject the same facts on every turn.

## Tools

\`memory_recall\`, \`memory_get\`, \`memory_recall_by_tag\`, \`memory_remember\`, \`memory_forget\`.

## Where memory lives

\`~/.builderforce-memory/memory.json\` — one store per machine, shared with every
other MCP host you have wired up (Cursor, Windsurf, VS Code, Claude Desktop, …)
via \`npx -y ${MCP_PACKAGE.replace(/^@/, "@")} builderforce-memory-install\`.
Override with \`BUILDERFORCE_MEMORY_FILE\`.

## License

MIT
`;
}
